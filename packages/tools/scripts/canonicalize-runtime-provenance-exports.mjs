import assert from "node:assert/strict";
import { rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

async function writeCanonicalFacade({ esmPath, cjsPath, cjsSpecifier }) {
  const canonical = require(resolve(packageRoot, cjsPath));
  const exportNames = Object.keys(canonical).sort();
  assert(exportNames.length > 0, `no runtime exports found in ${cjsPath}`);
  for (const name of exportNames) {
    assert.match(name, /^[A-Z_$][0-9A-Z_$]*$/i, `unsupported export: ${name}`);
  }

  const source = [
    "// Generated by scripts/canonicalize-runtime-provenance-exports.mjs.",
    "// Import and require share this canonical closure-backed implementation.",
    `import canonical from ${JSON.stringify(cjsSpecifier)};`,
    ...exportNames.map((name) => `export const ${name} = canonical.${name};`),
    "",
  ].join("\n");
  const outputPath = resolve(packageRoot, esmPath);
  await writeFile(outputPath, source);
  await rm(`${outputPath}.map`, { force: true });
}

await writeCanonicalFacade({
  esmPath: "dist/esm/index.js",
  cjsPath: "dist/cjs/index.js",
  cjsSpecifier: "../cjs/index.js",
});
await writeCanonicalFacade({
  esmPath: "dist/esm/_internal/agent-runtime-provenance.js",
  cjsPath: "dist/cjs/_internal/agent-runtime-provenance.js",
  cjsSpecifier: "../../cjs/_internal/agent-runtime-provenance.js",
});
