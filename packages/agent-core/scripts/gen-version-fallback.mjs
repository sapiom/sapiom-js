#!/usr/bin/env node
// Generates src/version-fallback.generated.ts from the workspace's own
// @sapiom/agent + @sapiom/tools package.json versions, and the zod version from
// the pnpm catalog in pnpm-workspace.yaml.
//
// Why this exists: scaffold.ts needs an OFFLINE fallback version to stamp into
// a scaffolded project when the live npm lookup fails. That value must always be
// a currently-published version. It used to be a hand-maintained constant, which
// silently drifted every time `changeset version` bumped the SDK without someone
// remembering to update it — breaking every offline scaffold and going red on
// every branch. Deriving it from the packages that actually get published means
// it can never drift again.
//
// Runs in two places so the committed file is always correct:
//   1. agent-core `prebuild` — regenerated on every build.
//   2. the root `version-packages` release step — regenerated in the same PR
//      that bumps the versions, so the release artifact ships the right value.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const versionOf = (pkgDir) =>
  JSON.parse(
    readFileSync(resolve(here, "..", "..", pkgDir, "package.json"), "utf8"),
  ).version;

const agent = versionOf("agent");
const tools = versionOf("tools");

// The default catalog is the repo's single source of the zod version; the scaffold
// pins its floor so new projects install the version the SDK is built against.
// Line-based read: the root has no YAML parser, and the block is flat `name: range`.
const catalogZod = () => {
  const yaml = readFileSync(
    resolve(here, "..", "..", "..", "pnpm-workspace.yaml"),
    "utf8",
  );
  const block = /^catalog:\n((?:[ \t]+.*\n?)*)/m.exec(yaml)?.[1] ?? "";
  const range = /^[ \t]+["']?zod["']?:[ \t]*["']?([^"'\s#]+)/m.exec(block)?.[1];
  const version = range?.replace(/^[\^~]/, "");
  if (!version || !/^\d+\.\d+\.\d+$/.test(version)) {
    throw new Error(
      `gen-version-fallback: no plain zod range in the pnpm-workspace.yaml catalog (got ${range})`,
    );
  }
  return version;
};
const zod = catalogZod();

const out = `// AUTO-GENERATED by packages/agent-core/scripts/gen-version-fallback.mjs.
// Do NOT edit by hand. Regenerated on every build (agent-core \`prebuild\`) and in
// the release \`version-packages\` step, so it always matches the workspace's
// @sapiom/agent + @sapiom/tools versions and the zod catalog entry, and the
// offline scaffold fallback can no longer drift.
export const VERSION_FALLBACK = {
  agent: ${JSON.stringify(agent)},
  tools: ${JSON.stringify(tools)},
  zod: ${JSON.stringify(zod)},
} as const;
`;

const outPath = resolve(here, "..", "src", "version-fallback.generated.ts");
writeFileSync(outPath, out);
console.log(`gen-version-fallback: agent=${agent} tools=${tools} zod=${zod}`);
